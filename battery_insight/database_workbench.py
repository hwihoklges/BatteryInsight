"""Read-only bridge from completed raw database runs to the workbench.

Only comparison metadata may be overridden by the database registration CSV.
Run/source/cell/test identities remain bound to the database manifest. No raw,
bronze, silver or gold table is copied or regenerated by this adapter.
"""
from __future__ import annotations

import copy
import hashlib
import json
import math
from pathlib import Path

import pandas as pd

from .experiment_updates import _bool, _load, validate_metrics
from .ingest import sha256_file
from .workbench_data import (CONTROL_FIELDS, MAX_TABLE_ROWS, build_workbench_bundle,
                             checked_artifact, json_safe, mapped_cycles, _cached_run_extras)


AXES = {"life_index": {"axis_label": "수명 cycle (life index)", "unit": "cycle", "is_lifetime": True},
        "rpt_internal_cycle": {"axis_label": "RPT 내부 cycle (수명 cycle 아님)", "unit": "cycle", "is_lifetime": False}}
IMMUTABLE = {"experiment_id", "cell_id", "test_id", "test_type", "run_path", "raw_path", "source_container",
             "source_id", "source_sha256", "status", "cell_identity_status", "source_row_basis"}
REFRESHED_SOURCE_FIELDS = {"run_path", "raw_path", "source_sha256", "status", "source_row_basis"}
EDITABLE = {"label", "cohort", "protocol", "chemistry", "temperature_c", "design_id", "design_group", "batch_id",
            "rpt_stage", "rpt_life_cycle", "include", "physical_cell_id"}


def _known(value):
    return value is not None and str(value).strip().lower() not in {"", "unknown", "unverified", "needs_review", "?", "none", "null", "nan"}


def _csv_text(value):
    return "" if value is None or isinstance(value, float) and math.isnan(value) else str(value)


def _registry_rows(root, manifest, config):
    entries = manifest.get("experiments")
    if not isinstance(entries, list) or any(not isinstance(row, dict) or not row.get("experiment_id") for row in entries):
        raise ValueError("Database manifest requires experiment rows with identities")
    by_id = {row["experiment_id"]: row for row in entries}
    if len(by_id) != len(entries):
        raise ValueError("Duplicate database experiment_id")
    registry = root / "experiments.csv"
    registry_hash = sha256_file(registry)
    frame = pd.read_csv(registry, dtype=str, keep_default_na=False, encoding="utf-8-sig")
    if sha256_file(registry) != registry_hash:
        raise ValueError("Database registry changed while reading; refresh again")
    required = {"experiment_id", "cell_id", "test_id", "test_type", "source_id"}
    if not required.issubset(frame):
        raise ValueError(f"Database registry is missing immutable identity columns: {sorted(required - set(frame))}")
    if frame.experiment_id.duplicated().any() or set(frame.experiment_id) - set(by_id):
        raise ValueError("Database registry has duplicate or unknown identities; use include=false to disable a test")
    editable = set(EDITABLE)
    numeric = {"temperature_c", "rpt_life_cycle"}
    for spec in config.get("design", {}).get("fields", []):
        editable.add(spec["field_id"])
        if spec["kind"] == "numeric":
            numeric.add(spec["field_id"])
        elif spec["kind"] == "composition":
            editable.update(spec["components"])
            numeric.update(spec["components"])
    for spec in config.get("workbench", {}).get("control_fields", CONTROL_FIELDS):
        editable.add(spec["field_id"])
        if spec["kind"] == "numeric":
            numeric.add(spec["field_id"])
    if editable & IMMUTABLE:
        raise ValueError("Design/control fields cannot override immutable database source identities")
    rows, issues = [], []
    overrides = {row["experiment_id"]: row for row in frame.to_dict("records")}
    for original in entries:
        identity = original["experiment_id"]
        override = overrides.get(identity, {})
        if not override:
            issues.append({"experiment_id": identity, "reason": "new_database_experiment_uses_manifest_metadata"})
        for key in (IMMUTABLE - REFRESHED_SOURCE_FIELDS) & set(override):
            if override[key] != _csv_text(original.get(key)):
                raise ValueError(f"Database registry cannot change immutable {key}: {identity}")
        stale = sorted(key for key in REFRESHED_SOURCE_FIELDS & set(override) if override[key] != _csv_text(original.get(key)))
        if stale:
            issues.append({"experiment_id": identity, "reason": "stale_registry_source_fields_ignored", "fields": stale,
                           "authority": "database_manifest"})
        row = copy.deepcopy(original)
        row.update({key: override[key] for key in editable & set(override)})
        row["include"] = _bool(row.get("include", True))
        for key in numeric:
            if key not in row:
                continue
            if not _known(row[key]):
                row[key] = None
                continue
            try:
                number = float(row[key])
            except (ValueError, TypeError) as exc:
                raise ValueError(f"Database metadata {key} must be numeric or missing") from exc
            if not math.isfinite(number):
                raise ValueError(f"Database metadata {key} must be finite")
            row[key] = number
        row["label"] = row.get("label") or row["experiment_id"]
        row["source_cell_id"] = original["cell_id"]
        if _known(row.get("physical_cell_id")):
            row["cell_id"] = str(row["physical_cell_id"]).strip()
            row["cell_identity_status"] = "mapped_physical_alias"
        rows.append(row)
    return rows, registry, registry_hash, issues


def checked_database_reference(reference):
    """Resolve one trusted reference and reverify its manifest/source binding."""
    root = Path(reference["database_path"]).resolve()
    run = Path(reference["run_path"]).resolve()
    if not run.is_relative_to(root / "runs"):
        raise ValueError("Database evidence run is outside database/runs")
    manifest_path = run / "run_manifest.json"
    if sha256_file(manifest_path) != reference["run_manifest_sha256"]:
        raise ValueError("Database run manifest changed; refresh the workbench")
    manifest = _load(manifest_path)
    if manifest.get("status") != "complete":
        raise ValueError("Database evidence requires a completed run")
    row = copy.deepcopy(reference["row"])
    row.setdefault("source_row_basis", manifest.get("source_row_basis", "1-based data record; not physical file line"))
    inputs = [item for item in manifest.get("identity", {}).get("inputs", [])
              if str(item.get("cell_id")) == str(row.get("source_cell_id", row["cell_id"])) and str(item.get("test_id")) == str(row["test_id"])]
    if len(inputs) != 1 or inputs[0].get("sha256") != reference["source_sha256"]:
        raise ValueError("Database source hash or cell/test identity differs from completed run")
    provenance = inputs[0]
    if row.get("source_id") and provenance.get("source_id") != row["source_id"]:
        raise ValueError("Database source_id differs from completed run")
    if row.get("source_container") and str(provenance.get("path")) != str(row["source_container"]):
        raise ValueError("Database source container differs from completed run")
    snapshot = _load(checked_artifact(run, "config_snapshot.json"))
    return row, run, provenance, snapshot


def _apply_knowledge_overlay(rows, overlay, root, config):
    """Join reviewed names/designs without changing immutable source identities."""
    from .raw_linking import apply_confirmed_links
    linked, issues = apply_confirmed_links(rows, overlay, root)
    original = {row['experiment_id']: row for row in rows}
    metadata = {row['experiment_id']: row.get('metadata', {}) for row in overlay.get('links', [])}
    for row in linked:
        if not row.get('knowledge_link'):
            continue
        supplied = metadata.get(row['experiment_id'], {})
        # A chart's active-only ratios cannot be compared as whole-electrode wt%.
        # Preserve the facts in the document registry but withhold incompatible
        # component values from this configured comparison.
        omitted = []
        for spec in config.get('design', {}).get('fields', []):
            if spec.get('kind') != 'composition':
                continue
            components = spec.get('components', [])
            contributed = [key for key in components if key in supplied]
            if not contributed:
                continue
            side = 'cathode' if all(key.startswith('cathode_') for key in components) else 'anode' if all(key.startswith('anode_') for key in components) else None
            basis = supplied.get(side + '_composition_basis') if side else None
            if not basis or basis != spec.get('composition_basis'):
                for key in contributed:
                    row[key] = original[row['experiment_id']].get(key)
                omitted.extend(contributed)
                issues.append({'experiment_id': row['experiment_id'], 'reason': 'knowledge_composition_basis_unverified',
                               'field_id': spec['field_id'], 'document_basis': basis,
                               'required_basis': spec.get('composition_basis'), 'withheld_fields': contributed})
        if omitted:
            row['knowledge_link']['unapplied_metadata_fields'] = sorted(set(omitted))
        if _known(row.get('physical_cell_id')):
            row['cell_id'] = str(row['physical_cell_id']).strip()
            row['cell_identity_status'] = 'mapped_physical_alias'
    return linked, issues


def build_database_bundle(config_path, output):
    """Return a current bundle backed by verified immutable database artifacts."""
    config_path, output = Path(config_path).resolve(), Path(output).resolve()
    config = _load(config_path)
    if config.get("schema_version") != 1 or not config.get("database_path"):
        raise ValueError("Database workbench config requires schema_version=1 and database_path")
    root = (config_path.parent / config["database_path"]).resolve()
    manifest_path = root / "database_manifest.json"
    manifest_hash = sha256_file(manifest_path)
    manifest = _load(manifest_path)
    if manifest.get("schema_version") != "raw_database_v1":
        raise ValueError("Unsupported raw database manifest schema")
    metrics = config.get("metrics", [])
    if metrics:
        validate_metrics(metrics)
    config["metrics"] = metrics
    rows, registry, registry_hash, registry_issues = _registry_rows(root, manifest, config)
    knowledge_context = None
    if config.get('knowledge_links'):
        if not isinstance(config['knowledge_links'], str):
            raise ValueError('knowledge_links must be an overlay JSON path')
        link_path = (config_path.parent / config['knowledge_links']).resolve()
        link_hash = sha256_file(link_path)
        overlay = _load(link_path)
        base_rows = copy.deepcopy(rows)
        rows, link_issues = _apply_knowledge_overlay(base_rows, overlay, root, config)
        registry_issues.extend(link_issues)
        knowledge_context = (link_path, link_hash, overlay, base_rows, copy.deepcopy(rows), link_issues)
    records, references, observations, issues, axis_records = [], {}, [], registry_issues, {}
    from . import metric_packs, workbench_data
    code_hashes = [sha256_file(Path(workbench_data.__file__)), sha256_file(Path(metric_packs.__file__))]
    external_specs = [spec for spec in metrics if spec.get("table") == "external_features"]
    run_extras = {}
    for row in rows:
        if not row["include"]:
            continue
        axis = "rpt_internal_cycle" if str(row["test_type"]).strip().lower() == "rpt" else "life_index"
        row.update(axis_kind=axis, axis_label=AXES[axis]["axis_label"])
        source_cohort = str(row.get("cohort") or row["experiment_id"])
        row["source_cohort"] = source_cohort
        protocol = str(row.get("protocol") or "")
        guard = protocol if _known(protocol) else row["experiment_id"]
        row["cohort"] = f"{source_cohort} [{axis}; protocol:{hashlib.sha256(guard.encode()).hexdigest()[:12]}]"
        axis_records[row["cohort"]] = {"cohort": row["cohort"], "source_cohort": source_cohort,
                                      "axis_kind": axis, "protocol": row.get("protocol"), **AXES[axis]}
        if not _known(protocol):
            issues.append({"experiment_id": row["experiment_id"], "reason": "protocol_unverified_comparison_isolated"})
        if row.get("status") != "complete":
            issues.append({"experiment_id": row["experiment_id"], "reason": "database_run_not_complete", "status": row.get("status")})
            continue
        run = Path(row["run_path"]).resolve()
        if not run.is_relative_to(root / "runs"):
            raise ValueError("Database completed run is outside database/runs")
        reference = {"database_path": str(root), "run_path": str(run), "source_sha256": row["source_sha256"],
                     "run_manifest_sha256": sha256_file(run / "run_manifest.json"), "row": copy.deepcopy(row)}
        checked_database_reference(reference)
        cycles = mapped_cycles(run, row)
        # Compute extras while this verified table is live, rather than holding
        # all experiments' full Gold tables or reopening them in a later pass.
        run_extras[row["experiment_id"]] = _cached_run_extras(output, run, row, external_specs,
                                                             cycles=cycles, code_hashes=code_hashes)
        for spec in metrics:
            if spec.get("table", "cycles") != "cycles":
                continue
            if spec["column"] not in cycles:
                issues.append({"experiment_id": row["experiment_id"], "metric_id": spec["metric_id"], "reason": "column_not_emitted"})
                continue
            for point in cycles[["cycle", "life_index", spec["column"]]].to_dict("records"):
                observations.append({"experiment_id": row["experiment_id"], "metric_id": spec["metric_id"],
                                     "life_index": point["life_index"], "cycle": point["cycle"], "axis_kind": axis,
                                     "observed_until_life": point["life_index"], "value": point[spec["column"]], "unit": spec["unit"]})
        if len(observations) > MAX_TABLE_ROWS:
            raise ValueError("Workbench observation row limit exceeded")
        references[row["experiment_id"]] = reference
        records.append({"experiment_id": row["experiment_id"], "run_path": str(run), "raw_sha256": row["source_sha256"], "status": "complete"})
    payload = {"schema_version": "database_workbench_v1", "ingestion": {"records": records}, "issues": issues,
               "database_path": str(root), "database_summary": manifest.get("summary", {})}
    bundle = build_workbench_bundle(output, config, rows, payload, observation_records=json_safe(observations),
                                    run_extras=run_extras)
    kinds = {record["axis_kind"] for record in axis_records.values()}
    axis_kind = next(iter(kinds)) if len(kinds) == 1 else "mixed" if kinds else "life_index"
    if sha256_file(manifest_path) != manifest_hash or sha256_file(registry) != registry_hash:
        raise ValueError("Database manifest or registry changed during analysis; refresh again")
    for reference in references.values():
        if sha256_file(Path(reference["run_path"]) / "run_manifest.json") != reference["run_manifest_sha256"]:
            raise ValueError("Completed database run changed during analysis; refresh again")
    if knowledge_context is not None:
        link_path, link_hash, overlay, base_rows, linked_rows, link_issues = knowledge_context
        refreshed_rows, refreshed_issues = _apply_knowledge_overlay(base_rows, overlay, root, config)
        if sha256_file(link_path) != link_hash or refreshed_rows != linked_rows or refreshed_issues != link_issues:
            raise ValueError('Document knowledge or reviewed links changed during analysis; refresh again')
        bundle['knowledge_summary'] = {'overlay_path': str(link_path), 'overlay_sha256': link_hash,
                                       'linked_experiments': sum(bool(row.get('knowledge_link')) for row in linked_rows),
                                       'issues': link_issues, 'source_registry': overlay.get('registry_path')}
    bundle.update(database_path=str(root), database_manifest_sha256=manifest_hash,
                  source_mode="database", evidence_references=references, registry_path=str(registry), registry_hash=registry_hash,
                  axis_kind=axis_kind, axis_label=AXES[axis_kind]["axis_label"] if axis_kind in AXES else "축은 비교군별 구분: 수명 cycle / RPT 내부 cycle",
                  axis_by_cohort=list(axis_records.values()), database_summary=manifest.get("summary", {}),
                  cell_identity_policy={"physical_alias_column": "physical_cell_id", "source_identity_column": "source_cell_id",
                                        "source_identity_mutable": False,
                                        "description": "physical_cell_id links confirmed same physical cells across tests; absent aliases retain source-specific provisional channel identities"},
                  capabilities={"registration": False, "registration_reason": f"DB 등록 메타데이터는 {registry} 파일을 편집한 뒤 새로고침하세요."})
    bundle["issues"] = issues + bundle["issues"]
    return json_safe(bundle)
